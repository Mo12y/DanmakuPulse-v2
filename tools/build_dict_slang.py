def main():
    base = 'config/dicts'
    # 梗表词（去重）
    meme_words = set()
    with open(os.path.join(base, 'meme_seed.tsv'), encoding='utf-8') as f:
        for line in f:
            if line.startswith('#') or not line.strip():
                continue
            meme_words.add(line.split('\t')[0])

    rows = {}
    # ① 手工表
    for ln in HAND.strip().split('\n'):
        w, wt, pol, tag = ln.split('|')
        rows[w] = (float(wt), int(pol), f'hand:{tag}')
    # ② DUT nw
    with open('/tmp/dutir_emotional.csv', encoding='utf-8') as f:
        r = csv.reader(f)
        next(r)
        n_nw = 0
        for row in r:
            if len(row) > 6 and row[1].strip() == 'nw' and row[0].strip():
                w = row[0].strip()
                try:
                    p = float(row[6])
                except ValueError:
                    continue
                if p not in (1.0, 2.0):
                    continue
                if w not in rows:
                    rows[w] = (2.0, 1 if p == 1.0 else -1, 'dut_nw')
                    n_nw += 1
    # ③ 剔除梗表重复
    for w in list(rows):
        if w in meme_words:
            del rows[w]

    with io.open(os.path.join(base, 'slang_v0.tsv'), 'w', encoding='utf-8') as f:
        f.write('# word\tweight\tpolarity\tsource（v0：手工+duT_nw；733 目标差距与候选队列见 CHANGELOG）\n')
        for w, (wt, pol, src) in sorted(rows.items()):
            f.write(f'{w}\t{wt}\t{pol}\t{src}\n')
    n_hand = sum(1 for v in rows.values() if v[2].startswith('hand'))
    print(f'slang_v0: {len(rows)} 词（手工 {n_hand} / dut_nw {len(rows) - n_hand}）'
          f'；剔除梗表重复后净额')


if __name__ == '__main__':
    main()
